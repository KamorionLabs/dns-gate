// Command gen generates the operation table of package routes from the
// EuroDNS OpenAPI document.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

func main() {
	spec := flag.String("spec", "../../api/eurodns.openapi.json", "OpenAPI document")
	out := flag.String("out", "zz_generated.go", "output file")
	flag.Parse()

	data, err := os.ReadFile(*spec)
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Info  struct{ Version string } `json:"info"`
		Paths map[string]map[string]struct {
			OperationID string `json:"operationId"`
		} `json:"paths"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		log.Fatal(err)
	}
	type op struct{ id, method, path string }
	var ops []op
	for path, methods := range doc.Paths {
		for m, o := range methods {
			switch m {
			case "get", "put", "post", "patch", "delete":
			default:
				continue
			}
			if o.OperationID == "" {
				log.Fatalf("%s %s: missing operationId", m, path)
			}
			ops = append(ops, op{o.OperationID, strings.ToUpper(m), path})
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].path != ops[j].path {
			return ops[i].path < ops[j].path
		}
		return ops[i].method < ops[j].method
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/routes/gen from api/eurodns.openapi.json (EuroDNS User API %s). DO NOT EDIT.\n\n", doc.Info.Version)
	b.WriteString("package routes\n\n")
	b.WriteString("var operations = []Operation{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q},\n", o.id, o.method, o.path)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
