// Package tfexport renders RRsets as Terraform/OpenTofu configuration: one
// record set resource per RRset and, unless disabled, an import block
// binding it to the existing RRset (Terraform or OpenTofu >= 1.5), with the
// import id "<zone>/<host>/<type>".
//
// The default provider is KamorionLabs/dnsgate (dnsgate_record_set), which
// talks to the gate REST API and works for every DNS provider behind the
// gate, alias RRsets included. ProviderEuroDNS targets the
// kamorionlabs/eurodns provider (eurodns_record_set) through the
// EuroDNS-compatible API; it has no alias RRsets.
package tfexport

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/KamorionLabs/dns-gate/internal/dns"
)

// Provider is the Terraform provider an export targets.
type Provider string

const (
	// ProviderDNSGate is the KamorionLabs/dnsgate provider (default).
	ProviderDNSGate Provider = "dnsgate"
	// ProviderEuroDNS is the kamorionlabs/eurodns provider.
	ProviderEuroDNS Provider = "eurodns"
)

// Source is the registry source of the provider.
func (p Provider) Source() string {
	if p == ProviderEuroDNS {
		return "registry.terraform.io/kamorionlabs/eurodns"
	}
	return "KamorionLabs/dnsgate"
}

func (p Provider) resourceType() string {
	if p == ProviderEuroDNS {
		return "eurodns_record_set"
	}
	return "dnsgate_record_set"
}

// ParseProvider returns the provider named s ("" is the default).
func ParseProvider(s string) (Provider, bool) {
	switch Provider(strings.ToLower(strings.TrimSpace(s))) {
	case "", ProviderDNSGate:
		return ProviderDNSGate, true
	case ProviderEuroDNS:
		return ProviderEuroDNS, true
	}
	return "", false
}

// Options tunes the output.
type Options struct {
	Provider       Provider // default ProviderDNSGate
	Header         []string // extra comment lines appended to the generated header
	ResourcePrefix string   // prepended to every resource name
	SkipImports    bool     // omit import blocks
}

const maxInlineList = 100

// Render returns HCL for the given RRsets. SOA and read-only RRsets are
// skipped, and alias RRsets for providers without alias. Output is
// deterministic: RRsets sorted by host then type, values sorted, stable
// resource names.
func Render(zone string, sets []dns.RRset, opts Options) string {
	zone = dns.NormalizeZone(zone)
	prov := opts.Provider
	if prov == "" {
		prov = ProviderDNSGate
	}
	kept := make([]dns.RRset, 0, len(sets))
	for _, s := range sets {
		if exportable(s, prov) {
			kept = append(kept, s)
		}
	}
	sort.Slice(kept, func(i, j int) bool { return kept[i].Key.Less(kept[j].Key) })

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by dns-gate for zone %s.\n", zone)
	fmt.Fprintf(&b, "# Provider: %s\n", prov.Source())
	if !opts.SkipImports {
		b.WriteString("# Import blocks require Terraform or OpenTofu >= 1.5; remove them once applied.\n")
	}
	for _, h := range opts.Header {
		for _, line := range strings.Split(h, "\n") {
			b.WriteString(strings.TrimRight("# "+line, " ") + "\n")
		}
	}

	rtype := prov.resourceType()
	used := map[string]bool{}
	for _, s := range kept {
		name := uniqueName(resourceName(opts.ResourcePrefix, s.Key), used)
		b.WriteString("\n")
		fmt.Fprintf(&b, "resource %q %s {\n", rtype, quote(name))
		if prov == ProviderEuroDNS {
			writeEuroDNS(&b, zone, s)
		} else {
			writeDNSGate(&b, zone, s)
		}
		b.WriteString("}\n")
		if !opts.SkipImports {
			b.WriteString("\nimport {\n")
			fmt.Fprintf(&b, "  to = %s.%s\n", rtype, name)
			fmt.Fprintf(&b, "  id = %s\n", quote(zone+"/"+s.Key.Host+"/"+s.Key.Type))
			b.WriteString("}\n")
		}
	}
	return b.String()
}

// attrs writes aligned attributes like terraform fmt: a multi-line value
// ends the alignment group.
func attrs(b *strings.Builder, indent string, kv [][2]string) {
	w := 0
	for _, p := range kv {
		if strings.Contains(p[1], "\n") {
			break
		}
		w = max(w, len(p[0]))
	}
	for _, p := range kv {
		if strings.Contains(p[1], "\n") {
			fmt.Fprintf(b, "%s%s = %s\n", indent, p[0], p[1])
			continue
		}
		fmt.Fprintf(b, "%s%-*s = %s\n", indent, w, p[0], p[1])
	}
}

func writeDNSGate(b *strings.Builder, zone string, s dns.RRset) {
	kv := [][2]string{{"zone", quote(zone)}, {"name", quote(s.Key.Host)}, {"type", quote(s.Key.Type)}}
	if s.Alias != nil {
		attrs(b, "  ", kv)
		b.WriteString("\n  alias {\n")
		attrs(b, "    ", [][2]string{
			{"name", quote(s.Alias.Target)},
			{"zone_id", quote(s.Alias.HostedZoneID)},
			{"evaluate_target_health", strconv.FormatBool(s.Alias.EvaluateTargetHealth)},
		})
		b.WriteString("  }\n")
		return
	}
	kv = append(kv, [2]string{"ttl", strconv.Itoa(s.TTL)}, [2]string{"values", list(sortedValues(s), "  ")})
	attrs(b, "  ", kv)
}

func writeEuroDNS(b *strings.Builder, zone string, s dns.RRset) {
	attrs(b, "  ", [][2]string{
		{"zone", quote(zone)}, {"host", quote(s.Key.Host)}, {"type", quote(s.Key.Type)},
		{"ttl", strconv.Itoa(s.TTL)}, {"values", list(sortedValues(s), "  ")},
	})
}

func sortedValues(s dns.RRset) []string {
	values := append([]string(nil), s.Values...)
	sort.Strings(values)
	return values
}

func exportable(s dns.RRset, p Provider) bool {
	switch {
	case strings.EqualFold(s.Key.Type, "SOA"), s.ReadOnly != "":
		return false
	case s.Alias != nil:
		return p != ProviderEuroDNS
	}
	return len(s.Values) > 0
}

// resourceName builds a valid Terraform identifier: letters, digits,
// underscores and dashes, starting with a letter or an underscore.
func resourceName(prefix string, k dns.Key) string {
	host := k.Host
	if host == dns.Apex || host == "" {
		host = "apex"
	}
	host = strings.ReplaceAll(host, "*", "wildcard")
	raw := strings.ToLower(prefix + host + "_" + k.Type)
	var b strings.Builder
	lastUnderscore := false
	for _, r := range raw {
		ok := (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-'
		if !ok {
			if !lastUnderscore {
				b.WriteByte('_')
			}
			lastUnderscore = true
			continue
		}
		b.WriteRune(r)
		lastUnderscore = false
	}
	name := strings.Trim(b.String(), "_-")
	if name == "" {
		name = "record_set"
	}
	if c := name[0]; c >= '0' && c <= '9' {
		name = "r_" + name
	}
	return name
}

func uniqueName(name string, used map[string]bool) string {
	out := name
	for i := 2; used[out]; i++ {
		out = name + "_" + strconv.Itoa(i)
	}
	used[out] = true
	return out
}

// quote returns an HCL quoted string. Template sequences are escaped so that
// TXT contents such as "${x}" or "%{x}" stay literal. Input comes from JSON
// and is valid UTF-8.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); {
		r, size := utf8.DecodeRuneInString(s[i:])
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '"':
			b.WriteString(`\"`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case (r == '$' || r == '%') && i+1 < len(s) && s[i+1] == '{':
			b.WriteRune(r)
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, "\\u%04X", r)
		default:
			b.WriteRune(r)
		}
		i += size
	}
	b.WriteByte('"')
	return b.String()
}

func list(values []string, indent string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = quote(v)
	}
	inline := "[" + strings.Join(quoted, ", ") + "]"
	if len(inline) <= maxInlineList && len(values) <= 4 {
		return inline
	}
	var b strings.Builder
	b.WriteString("[\n")
	for _, q := range quoted {
		b.WriteString(indent + "  " + q + ",\n")
	}
	b.WriteString(indent + "]")
	return b.String()
}
