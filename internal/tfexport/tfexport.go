// Package tfexport renders RRsets as Terraform/OpenTofu configuration for the
// registry.terraform.io/kamorionlabs/eurodns provider: one eurodns_record_set
// resource per RRset and, unless disabled, an import block binding it to the
// existing upstream RRset (Terraform or OpenTofu >= 1.5).
package tfexport

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/KamorionLabs/eurodns-go/rrset"
)

// ProviderSource is the provider the generated configuration targets.
const ProviderSource = "registry.terraform.io/kamorionlabs/eurodns"

// Options tunes the output.
type Options struct {
	Header         []string // extra comment lines appended to the generated header
	ResourcePrefix string   // prepended to every resource name
	SkipImports    bool     // omit import blocks
}

const maxInlineList = 100

// Render returns HCL for the given RRsets. SOA and locked (server-managed)
// RRsets are skipped. Output is deterministic: RRsets sorted by host then
// type, values sorted, stable resource names.
func Render(zone string, sets []rrset.Set, opts Options) string {
	zone = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(zone)), ".")
	kept := make([]rrset.Set, 0, len(sets))
	for _, s := range sets {
		if !serverManaged(s) {
			kept = append(kept, s)
		}
	}
	sort.Slice(kept, func(i, j int) bool {
		if kept[i].Key.Host != kept[j].Key.Host {
			return kept[i].Key.Host < kept[j].Key.Host
		}
		return kept[i].Key.Type < kept[j].Key.Type
	})

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by eurodns-gate for zone %s.\n", zone)
	fmt.Fprintf(&b, "# Provider: %s\n", ProviderSource)
	if !opts.SkipImports {
		b.WriteString("# Import blocks require Terraform or OpenTofu >= 1.5; remove them once applied.\n")
	}
	for _, h := range opts.Header {
		for _, line := range strings.Split(h, "\n") {
			b.WriteString(strings.TrimRight("# "+line, " ") + "\n")
		}
	}

	used := map[string]bool{}
	for _, s := range kept {
		name := uniqueName(resourceName(opts.ResourcePrefix, s.Key), used)
		values := append([]string(nil), s.Values...)
		sort.Strings(values)
		b.WriteString("\n")
		fmt.Fprintf(&b, "resource \"eurodns_record_set\" %s {\n", quote(name))
		vals := list(values, "  ")
		// Like terraform fmt: a multi-line value ends the alignment group.
		w := 6
		if strings.Contains(vals, "\n") {
			w = 4
		}
		fmt.Fprintf(&b, "  %-*s = %s\n", w, "zone", quote(zone))
		fmt.Fprintf(&b, "  %-*s = %s\n", w, "host", quote(s.Key.Host))
		fmt.Fprintf(&b, "  %-*s = %s\n", w, "type", quote(s.Key.Type))
		fmt.Fprintf(&b, "  %-*s = %d\n", w, "ttl", s.TTL)
		fmt.Fprintf(&b, "  values = %s\n", vals)
		b.WriteString("}\n")
		if !opts.SkipImports {
			b.WriteString("\nimport {\n")
			fmt.Fprintf(&b, "  to = eurodns_record_set.%s\n", name)
			fmt.Fprintf(&b, "  id = %s\n", quote(zone+"/"+s.Key.Host+"/"+s.Key.Type))
			b.WriteString("}\n")
		}
	}
	return b.String()
}

func serverManaged(s rrset.Set) bool {
	if strings.EqualFold(s.Key.Type, "SOA") {
		return true
	}
	for _, r := range s.Records {
		if rrset.ServerManaged(r) {
			return true
		}
	}
	return false
}

// resourceName builds a valid Terraform identifier: letters, digits,
// underscores and dashes, starting with a letter or an underscore.
func resourceName(prefix string, k rrset.Key) string {
	host := k.Host
	if host == rrset.Apex || host == "" {
		host = "apex"
	}
	host = strings.ReplaceAll(host, "*", "wildcard")
	raw := strings.ToLower(prefix + host + "_" + k.Type)
	var b strings.Builder
	lastUnderscore := false
	for _, r := range raw {
		ok := (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-'
		if !ok {
			if !lastUnderscore {
				b.WriteByte('_')
			}
			lastUnderscore = true
			continue
		}
		b.WriteRune(r)
		lastUnderscore = false
	}
	name := strings.Trim(b.String(), "_-")
	if name == "" {
		name = "record_set"
	}
	if c := name[0]; c >= '0' && c <= '9' {
		name = "r_" + name
	}
	return name
}

func uniqueName(name string, used map[string]bool) string {
	out := name
	for i := 2; used[out]; i++ {
		out = name + "_" + strconv.Itoa(i)
	}
	used[out] = true
	return out
}

// quote returns an HCL quoted string. Template sequences are escaped so that
// TXT contents such as "${x}" or "%{x}" stay literal. Input comes from JSON
// and is valid UTF-8.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); {
		r, size := utf8.DecodeRuneInString(s[i:])
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '"':
			b.WriteString(`\"`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case (r == '$' || r == '%') && i+1 < len(s) && s[i+1] == '{':
			b.WriteRune(r)
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, "\\u%04X", r)
		default:
			b.WriteRune(r)
		}
		i += size
	}
	b.WriteByte('"')
	return b.String()
}

func list(values []string, indent string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = quote(v)
	}
	inline := "[" + strings.Join(quoted, ", ") + "]"
	if len(inline) <= maxInlineList && len(values) <= 4 {
		return inline
	}
	var b strings.Builder
	b.WriteString("[\n")
	for _, q := range quoted {
		b.WriteString(indent + "  " + q + ",\n")
	}
	b.WriteString(indent + "]")
	return b.String()
}
